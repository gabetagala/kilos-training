// Build app/data.js from the enriched 72-venue scrape + Places sweep metadata.
//   node scripts/gen-app-data.mjs

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const seed = JSON.parse(readFileSync(join(ROOT, 'seed-data', 'seed-venues.json'), 'utf8'));
const classified = JSON.parse(readFileSync(join(ROOT, 'seed-data', 'classified.json'), 'utf8'));
const photos = existsSync(join(ROOT, 'seed-data', 'photo-map.json'))
  ? JSON.parse(readFileSync(join(ROOT, 'seed-data', 'photo-map.json'), 'utf8'))
  : {};
const photoSlug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);

const norm = (n) =>
  n.toLowerCase().replace(/\(.*?\)/g, '').replace(/\b(the|resort and spa|resort & spa|hotel|tagaytay|manila|cebu|boracay)\b/g, '').replace(/[^a-z0-9]/g, '');
const places = new Map(classified.map((p) => [norm(p.name), p]));

const region = (area) => {
  if (/metro manila/i.test(area)) return 'Metro Manila';
  if (/cavite/i.test(area)) return 'Tagaytay';
  if (/batangas|la union|zambales|quezon\b/i.test(area)) return 'Beach North';
  if (/aklan|boracay/i.test(area)) return 'Boracay';
  if (/cebu/i.test(area)) return 'Cebu';
  if (/bohol|palawan|negros|leyte|zamboanga|davao/i.test(area)) return 'Islands South';
  return 'More PH';
};

const typeLabel = (t) =>
  (t ?? 'venue').replace(/_/g, ' ').replace(/\b(bed & breakfast|b&b)\b/i, 'B&B').toUpperCase();

// The FIRST year in the notes is the one attached to the starting rate; later
// years are usually "site checked in <year>, still no prices" mentions. Taking
// the max dated a 2024 rate as 2026 — wrong on the field couples trust most.
const rateYear = (notes) => {
  const m = (notes ?? '').match(/20(1[4-9]|2[0-6])/);
  return m ? Number(m[0]) : null;
};

const venues = seed
  .map((v) => {
    const p = places.get(norm(v.name));
    const year = rateYear(v.rate_notes);
    const shot = photos[photoSlug(v.name.replace(/ \(.*?\)$/, ''))];
    return {
      photo: shot?.file ?? null,
      credit: shot?.attribution ?? null,
      name: v.name.replace(/ \(.*?\)$/, ''),
      area: v.area.replace(/ ?\(.*?\)/g, ''),
      region: region(v.area),
      type: typeLabel(v.type),
      capacity: v.capacity ?? null,
      rate: v.starting_rate_php ?? null,
      rateYear: year,
      fresh: v.starting_rate_php != null && year != null && year >= 2024,
      notes: (v.rate_notes ?? '').split(/(?<=\.)\s/)[0].slice(0, 180),
      maps: p?.google_maps_uri ?? null,
      website: v.website ?? null,
      rating: p?.rating ?? null,
      reviews: p?.user_ratings ?? null,
    };
  })
  // per-head + tiny partial rates mislead as "from" prices in a list; keep them out of v1
  .filter((v) => v.rate == null || v.rate >= 8000)
  // photographed venues first — the list should look alive from the first screen
  .sort((a, b) => (b.photo ? 1 : 0) - (a.photo ? 1 : 0) || (b.reviews ?? 0) - (a.reviews ?? 0));

const meta = {
  swept: 4170,       // Places sweep, 2026-08-17
  researched: venues.length,   // what actually ships, not what was scraped
  priced: venues.filter((v) => v.rate != null).length,
  hidden: venues.filter((v) => v.rate == null).length,
};

mkdirSync(join(ROOT, 'app'), { recursive: true });
writeFileSync(
  join(ROOT, 'app', 'data.js'),
  `// generated by scripts/gen-app-data.mjs — do not edit by hand\nwindow.WD_META = ${JSON.stringify(meta)};\nwindow.WD_VENUES = ${JSON.stringify(venues, null, 1)};\n`
);
console.log(`app/data.js: ${venues.length} venues (${meta.priced} priced, ${meta.hidden} hidden), regions:`,
  [...new Set(venues.map((v) => v.region))].join(', '));
