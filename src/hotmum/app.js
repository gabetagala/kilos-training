// preloading the whole vocabulary two times over.
//
// Every movement is stored with kind 'walk'. That's deliberate: the weekly
// target, the sync dedup key and two years of her history all count walks, and
// a yoga day that didn't count as showing up would be a worse bug than an
// imprecise field name. `moveId` carries which one it was.
function buildWalkRun(moveId = 'walk') {
  const move = getMovement(moveId);
  run = {
    kind: 'walk',
    moveId: move.id,
    queue: [
      {
        kind: 'work',
        exId: 'walk',
        secs: move.mins * 60,
        phase: move.name.toUpperCase(),
        meta: `${move.mins} MINUTES`,
      },
    ],
    idx: 0,
    elapsed: 0,
    running: true,
    since: Date.now(),
    totals: { secs: 0, sets: 0, tut: 0 },
    deltas: [],
    startedAt: Date.now(),
  };
}

function startMove(moveId = 'walk') {
  buildWalkRun(moveId);
  enterPlayer();
}

// What the coach says when a step BEGINS. Called on entering the player and
// on every advance — the first step of a session is a step too, and it used
// to start in silence.
function announce(st) {
  if (!st) return;
  hush();
  if (st.kind === 'prep') {
    say('get-set');
    // …then name what's coming, so she can set up without reading the screen.
    // Queued, not timed — a fixed 900ms delay landed on top of longer names.
    sayAfter(`name-${st.exId}`);
  } else if (st.kind === 'rest') {
    // The engine calls the short re-brace between McGill-style reps BREATHE.
    if (st.phase === 'SWITCH SIDES') say('switch-sides');
    else if (st.phase === 'BREATHE') say('breathe');
    else say('rest');
  } else if (st.tempo) {
    say('go');
  } else if (st.kind === 'work') {
    // A walk or a yoga class is one long step with no reps in it — it opens
    // with "go", not with "hold", which is what the rep fallback used to say.
    if (run.kind !== 'session') say('go');
    // Timed holds (wall sits, carries, suitcase holds) had no voice at all.
    // Call the rep so she knows where she is in the set.
    else say(NUM_SLUGS[st.rep] || 'hold');
  }
}

function enterPlayer() {
  view = 'player';
  lastBeat = '';
  keepAwake(true);
  // Decode everything this session will say BEFORE the first set — decoding
  // mid-beat is what makes a word land late.
  preload([
    ...Object.values(PHASE_WORDS),
    ...NUM_SLUGS.filter(Boolean),
    'get-set',
    'go',
    'rest',
    'breathe',
    'switch-sides',
    'last-three',
    'last-one',
    'session-complete',
    ...new Set(
      run.queue
        .filter((st) => HOTMUM_EXERCISES[st.exId])
        .map((st) => `name-${st.exId}`),
    ),
  ]);
  renderPlayer();
  announce(step());
  tick();
}

// ─── The player ────────────────────────────────────────────────────────────

const elapsedMs = () =>
  run.elapsed + (run.running ? Date.now() - run.since : 0);

const step = () => run.queue[run.idx];

// ─── What it looks like, and what to feel ──────────────────────────────────
// The gap this closes: the player knew the name, the tempo and the seconds,
// and showed none of what a beginner actually needs — the shape of the
// movement, and the two sentences about what it should feel like and what to
// watch for. That copy has been in program.js since day one; it was only ever
// rendered on a card she'd have to go looking for, which is no use mid-set.
//
// The figure is on screen the whole time. The words are NOT: during a tempo
// set the phase word owns the screen, because reading prose while counting a
// three-second lower is not a thing anyone does. They show when she's setting
// up (prep) and when she's resting — the two moments she's looking rather
// than moving, and during a rest they describe what's COMING, not what's done.

/** The exercise the screen should be teaching right now. */
function teachingId(st, idx) {
  if (st.kind !== 'rest') return st.exId;
  const next = run.queue.slice(idx + 1).find((q) => q.kind === 'work');
  return next?.exId || st.exId;
}

function guideFor(exId) {
  const ex = HOTMUM_EXERCISES[exId];
  if (!ex) return '';
  return `
    <div class="pl-guide">
      <p class="g-row g-feel"><b>FEEL</b><span>${esc(ex.feel)}</span></p>
      <p class="g-row g-avoid"><b>AVOID</b><span>${esc(ex.avoid)}</span></p>
      ${ex.knee ? `<p class="g-row g-knee"><b>KNEE</b><span>${esc(ex.knee)}</span></p>` : ''}
    </div>`;
}

function renderPlayer() {
  const st = step();
  const ex = HOTMUM_EXERCISES[st.exId];
  const isWalk = run.kind === 'walk';
  const teach = isWalk ? null : teachingId(st, run.idx);
  // Resting is when she wants to know what's coming — a rest step's own exId
  // is the move she just finished, so ask the queue instead.
  const cue =
    st.kind === 'rest'
      ? `Next — ${nextWorkLabel(run.queue, run.idx)}`
      : st.kind === 'prep' || st.kind === 'work'
        ? ex?.cue || ''
        : '';
  const teaching = st.kind === 'prep' || st.kind === 'rest';

  app.innerHTML = `
    <div class="screen player" id="pl">
      <div class="bloom"></div>
      <div class="pl-top">
        <div class="ex-name">${esc(isWalk ? getMovement(run.moveId).name.toUpperCase() : exName(st.exId))}</div>
        <button class="icon-btn" id="quit" aria-label="End session">✕</button>
      </div>

      <div class="pl-mid">
        ${teach ? `<div class="hm-demo${teaching ? ' teaching' : ''}" id="demo">${demoFor(teach)}</div>` : ''}
        <div class="timer" id="timer">0:00</div>
        <div class="phase" id="phase">${esc(st.phase || '')}</div>
        <p class="cue" id="cue">${esc(cue)}</p>
        <span class="lbl lbl-sm" id="meta">${esc(st.meta || '')}</span>
        ${teaching && teach ? guideFor(teach) : ''}
        <div class="pips" id="pips"></div>
        <div class="strip">
          <span class="lbl lbl-sm" id="tempo-lbl"></span>
          <span class="lbl lbl-sm" id="load-lbl"></span>
        </div>
      </div>

      <div class="pl-foot">
        <div class="btn-row">
          <button class="btn btn-ghost btn-sm" id="back" aria-label="Previous step" ${run.idx === 0 ? 'disabled' : ''}>BACK</button>
          <button class="btn btn-ghost" id="pause">${run.running ? 'PAUSE' : 'RESUME'}</button>
          <button class="btn btn-ghost btn-sm" id="skip" aria-label="Skip this step">SKIP</button>
        </div>
        <div class="prog"><i id="prog" style="width:0%"></i></div>
      </div>
    </div>`;

  app.querySelector('#pause').addEventListener('click', togglePause);
  app.querySelector('#back').addEventListener('click', stepBack);
  app.querySelector('#skip').addEventListener('click', () => advance(true));
  app.querySelector('#quit').addEventListener('click', endEarly);
  paintStatic();
}

// Reduced motion freezes every figure at its working position (each pose is
// drawn contracted for exactly this reason) — same contract as KILOS.
function freezeDemoIfAsked() {
  if (!window.matchMedia?.('(prefers-reduced-motion: reduce)')?.matches) return;
  for (const a of app.querySelectorAll('#demo animate, #demo animateTransform'))
    a.remove();
}

function paintStatic() {
  const st = step();
  const blk = st.tempo;
  const tempoLbl = app.querySelector('#tempo-lbl');
  const loadLbl = app.querySelector('#load-lbl');
  freezeDemoIfAsked();
  if (tempoLbl)
    tempoLbl.textContent = blk
      ? `TEMPO ${blk.pattern.map(([, s]) => s).join('-')}`
      : '';
  if (loadLbl) {
    const b = findBlock(st);
    loadLbl.textContent = b?.load
      ? formatLoad(b.load, profile.unit).toUpperCase()
      : '';
  }
  const pips = app.querySelector('#pips');
  if (pips) {
    pips.innerHTML = blk
      ? Array.from({ length: blk.reps }, () => '<i class="pip"></i>').join('')
      : '';
  }
}

// The block a step came from — the engine tags steps with `bi`.
function findBlock(st) {
  if (run.kind !== 'session' || st.bi == null) return null;
  const session = runSession();
  return stageSession(session, run.stages[run.stagePos]).blocks[st.bi] || null;
}

function tick() {
  cancelAnimationFrame(raf);
  const frame = () => {
    if (view !== 'player' || !run) return;
    const st = step();
    const e = elapsedMs();
    const total = (st.secs ?? 0) * 1000;

    const timer = app.querySelector('#timer');
    if (timer) timer.textContent = mmss((total - e) / 1000);

    const pl = app.querySelector('#pl');
    if (st.tempo) {
      const ts = tempoStateAt(st.tempo, e);
      const phase = app.querySelector('#phase');
      if (phase) phase.textContent = ts.label;
      const meta = app.querySelector('#meta');
      if (meta)
        meta.textContent = `${st.meta} · REP ${ts.rep} OF ${st.tempo.reps}`;
      if (pl) pl.className = `screen player ${ts.label.toLowerCase()}`;
      for (const [i, p] of [...app.querySelectorAll('.pip')].entries()) {
        p.className = `pip${i < ts.rep - 1 ? ' on' : i === ts.rep - 1 ? ' now' : ''}`;
      }
      // one spoken beat per phase-second boundary
      const key = `${ts.rep}:${ts.label}:${ts.phaseSec}`;
      if (key !== lastBeat) {
        lastBeat = key;
        say(beatSlug(ts, st.tempo));
      }
    } else {
      if (pl)
        pl.className = `screen player${st.kind === 'rest' ? ' resting' : ''}`;
      // 3-2-1 into the end of a timed HOLD only. A rest already said "rest"
      // when it began; counting it down again fills the one quiet part.
      if (st.kind === 'work') {
        const left = (total - e) / 1000;
        const cd = countdownSlug(left);
        const key = cd ? `cd${Math.ceil(left)}` : '';
        if (cd && key !== lastBeat) {
          lastBeat = key;
          say(cd);
        }
      }
    }

    const prog = app.querySelector('#prog');
    if (prog)
      prog.style.width = `${((run.idx + e / (total || 1)) / run.queue.length) * 100}%`;

    if (Date.now() - lastSave > 2000) save();
    if (st.secs != null && e >= total) advance();
    else raf = requestAnimationFrame(frame);
  };
  raf = requestAnimationFrame(frame);
}

function advance(skipped = false) {
  const st = step();
  const delta = { sets: 0, tut: 0, secs: Math.round(elapsedMs() / 1000) };
  if (st.kind === 'work') {
    if (st.countsAsSet) delta.sets = 1;
    if (!skipped) delta.tut = st.secs || 0;
  }
  run.totals.sets += delta.sets;
  run.totals.tut += delta.tut;
  run.totals.secs += delta.secs;
  if (!run.deltas) run.deltas = [];
  run.deltas.push(delta);

  run.idx++;
  run.elapsed = 0;
  run.since = Date.now();
  lastBeat = '';

  if (run.idx >= run.queue.length) return stageComplete();

  announce(step());

  save();
  renderPlayer();
  tick();
}

// ─── End of a stage: offer to keep going ───────────────────────────────────

function stageComplete() {
  cancelAnimationFrame(raf);
  if (run.kind === 'walk') return finishRun();

  const atLast = run.stagePos >= run.stages.length - 1;
  const nextStage = run.stages[run.stagePos + 1];

  // FULL and CORE were chosen up front — don't interrupt them.
  if (!atLast && nextStage != null) {
    run.stagePos++;
    startStage();
    return;
  }
  // SHORT: the session grows only if she says yes.
  const grown = lastRunStage() + 1;
  if (run.dose === 'short' && grown < STAGES.length) return askExtend(grown);
  finishRun();
}

const lastRunStage = () => run.stages[run.stagePos];

function startStage() {
  const session = runSession();
  run.queue = buildStepQueue(stageSession(session, run.stages[run.stagePos]));
  run.deltas = [];
  run.idx = 0;
  run.elapsed = 0;
  run.since = Date.now();
  run.running = true;
  save();
  renderPlayer();
  tick();
}

function askExtend(stageIdx) {
  view = 'ask';
  const session = runSession();
  const mins = stageMins(session, stageIdx);
  const ask = `Add the ${stageName(session, stageIdx).toLowerCase()}?`;
  app.innerHTML = `
    <div class="screen">
      <div class="top"><div class="mark">HOT<br>MUM</div></div>
      <div class="ask">
        <span class="lbl lbl-sm lbl-hot">THAT'S THE MAIN WORK DONE</span>
        <h2>${esc(ask)}</h2>
        <p class="blurb">+${mins} min. Stop here and it still counts as a full session.</p>
      </div>
      <div style="flex-shrink:0">
        <button class="btn" id="yes">KEEP GOING</button>
        <div class="btn-row"><button class="btn btn-ghost btn-sm" id="no">I'M DONE</button></div>
      </div>
    </div>`;
  app.querySelector('#yes').addEventListener('click', () => {
    run.stages = [...run.stages, stageIdx];
    run.stagePos = run.stages.length - 1;
    view = 'player';
    startStage();
  });
  app.querySelector('#no').addEventListener('click', finishRun);
}

// ─── Finishing ─────────────────────────────────────────────────────────────

/** The ✕ asks first — a mis-tap mid-set shouldn't end twenty minutes of work. */
function endEarly() {
  const sets = run.totals.sets;
  // Pause the clock while she decides; the dialog shouldn't cost her seconds.
  const wasRunning = run.running;
  if (wasRunning) togglePause();

  const quit = () => {
    drop(K.active);
    run = null;
    view = 'home';
    keepAwake(false);
    cancelAnimationFrame(raf);
    renderHome();
  };

  const sheet = document.createElement('div');
  sheet.className = 'sheet';
  sheet.innerHTML = `<div class="sheet-card" role="dialog" aria-label="End the session">
      <div class="sheet-top"><h3>${sets ? 'Done for today?' : 'Leave this session?'}</h3></div>
      <p class="row-s">${
        sets
          ? `You've done ${sets} set${sets === 1 ? '' : 's'}. Finish here and they're saved — it still counts as a session.`
          : "Nothing's been logged yet, so there's nothing to save."
      }</p>
      <button class="btn" id="q-stay">KEEP GOING</button>
      <div class="btn-row">
        ${sets ? '<button class="btn btn-ghost btn-sm" id="q-finish">FINISH &amp; SAVE</button>' : ''}
        <button class="btn btn-ghost btn-sm" id="q-quit">${sets ? 'DISCARD' : 'LEAVE'}</button>
      </div>
    </div>`;
  document.body.appendChild(sheet);

  const close = () => {
    sheet.remove();
    if (wasRunning && run && !run.running) togglePause(); // pick the clock back up
  };
  sheet.querySelector('#q-stay').addEventListener('click', close);
  sheet.querySelector('#q-finish')?.addEventListener('click', () => {
    sheet.remove();
    finishRun();
  });
  sheet.querySelector('#q-quit').addEventListener('click', () => {
    sheet.remove();
    quit();
  });
  sheet.addEventListener('click', (e) => {
    if (e.target === sheet) close();
  });
}

function finishRun() {
  cancelAnimationFrame(raf);
  keepAwake(false);
  say('session-complete');
  const rec = {
    kind: run.kind,
    sessionId: run.sessionId,
    moveId: run.moveId,
    dose: run.dose,
    secs: run.totals.secs,
    sets: run.totals.sets,
    tut: run.totals.tut,
  };
  logDone(rec);
  drop(K.active);
  const done = { ...rec };
  run = null;
  renderFinish(done);
}

function logDone(rec) {
  const list = history();
  list.push({ date: todayKey(), at: Date.now(), ...rec });
  set(K.history, list.slice(-400));
  queuePush(); // fire-and-forget; the loop never waits on the network
}

function renderFinish(rec) {
  view = 'finish';
  const day = dayNumber();
  const isWalk = rec.kind === 'walk';
  const move = isWalk ? getMovement(rec.moveId) : null;
  const session = rec.sessionId ? getSession(rec.sessionId) : null;
  const title = isWalk ? dayTitle(move.name) : dayTitle(session.name);

  app.innerHTML = `
    <div class="screen finish">
      <div class="top">
        <span class="lbl lbl-sm">${isWalk ? 'MOVEMENT LOGGED' : 'SESSION COMPLETE'}</span>
        <span class="lbl lbl-sm">DAY ${day} OF ${SEASON.days}</span>
      </div>
      <div class="poster-type">
        <div class="pt-row"><span>${esc(SEASON.label)}</span><u>${isWalk ? 'SHE SHOWED UP' : 'SHE LIFTED IT'}</u><span>2026</span></div>
        <div>ATTN :: ${esc(profile.name.toUpperCase())}</div>
      </div>
      <div class="hero">
        <div class="day-name">${title}</div>
      </div>
      <div class="fin-grid">
        <div class="fin-cell"><b>${mmss(rec.secs)}</b><span class="lbl lbl-sm">TIME</span></div>
        <div class="fin-cell"><b>${isWalk ? move.mins : rec.sets}</b><span class="lbl lbl-sm">${isWalk ? 'MINUTES' : 'SETS'}</span></div>
        ${
          isWalk
            ? `<div class="fin-cell"><b>${history().filter((h) => h.kind === 'walk').length}</b><span class="lbl lbl-sm">MOVEMENT DAYS</span></div>`
            : `<div class="fin-cell"><b>${mmss(rec.tut)}</b><span class="lbl lbl-sm">UNDER TENSION</span></div>`
        }
        <div class="fin-cell"><b>${daysToGo()}</b><span class="lbl lbl-sm">DAYS TO GO</span></div>
      </div>
      <div class="fin-tag">
        <div class="fin-mark">HOT<br><em>MUM</em></div>
        <span class="lbl lbl-sm">HOT AS IN STRONG</span>
      </div>
      <div class="btn-row">
        <button class="btn" id="home">DONE</button>
        <button class="btn btn-share" id="share">SHARE</button>
      </div>
    </div>`;
  app.querySelector('#home').addEventListener('click', () => {
    view = 'home';
    renderHome();
  });
  app.querySelector('#share').addEventListener('click', () => openShare(rec));
}

// ─── Pause / persist / restore ─────────────────────────────────────────────

/** Redo the step before this one — she lost her place, or wants it again. */
function stepBack() {
  if (!run || run.idx === 0) return;
  const d = run.deltas?.pop();
  if (d) {
    run.totals.sets -= d.sets;
    run.totals.tut -= d.tut;
    run.totals.secs -= d.secs;
  }
  run.idx--;
  run.elapsed = 0;
  run.since = Date.now();
  run.running = true;
  lastBeat = '';
  save();
  renderPlayer();
  announce(step());
  tick();
}

function togglePause() {
  if (run.running) {
    run.elapsed += Date.now() - run.since;
    run.running = false;
  } else {
    run.since = Date.now();
    run.running = true;
  }
  save();
  renderPlayer();
  if (run.running) tick();
}

function save() {
  if (!run) return;
  lastSave = Date.now();
  set(K.active, {
    ...run,
    queue: undefined, // rebuilt from the program on restore
    elapsed: elapsedMs(),
    since: Date.now(),
    savedAt: Date.now(),
  });
}

function restore() {
  const s = get(K.active);
  if (!s) return false;
  // Anything older than 6 hours is a forgotten session, not a paused one.
  if (Date.now() - (s.savedAt || 0) > 6 * 3600 * 1000) {
    drop(K.active);
    return false;
  }
  if (s.kind === 'walk') {
    // Build the movement run WITHOUT entering the player — startMove() would
    // enter it here and again below, announcing "go" twice and preloading twice.
    buildWalkRun(s.moveId);
    run.idx = s.idx;
    run.elapsed = s.elapsed;
    run.totals = s.totals || run.totals;
  } else {
    const session = prepped(s.sessionId, {
      easyKnee: s.easyKnee,
      day: s.day,
    });
    if (!session) {
      drop(K.active);
      return false;
    }
    run = {
      ...s,
      queue: buildStepQueue(stageSession(session, s.stages[s.stagePos])),
    };
    if (run.idx >= run.queue.length) {
      drop(K.active);
      return false;
    }
  }
  run.running = false; // always resume paused — she may not be holding the phone
  run.since = Date.now();
  enterPlayer();
  return true;
}

for (const ev of ['pagehide', 'visibilitychange']) {
  window.addEventListener(ev, () => {
    if (run && view === 'player') save();
  });
}
// iOS suspends the AudioContext whenever the app is backgrounded — coming back
// to a silent coach mid-session is exactly the bug this whole module exists for.
document.addEventListener('visibilitychange', () => {
  if (!document.hidden) resumeIfNeeded();
});

// Escape closes the topmost sheet. Every sheet is dismissible by tapping the
// backdrop or the ✕; on a laptop the key is what people actually reach for.
document.addEventListener('keydown', (e) => {
  if (e.key !== 'Escape') return;
  const sheets = document.querySelectorAll('.sheet');
  const top = sheets[sheets.length - 1];
  if (!top) return;
  // The quit dialog owns its own dismissal — it has to un-pause the clock.
  const stay = top.querySelector('#q-stay');
  if (stay) stay.click();
  else top.remove();
});

// ─── Boot ──────────────────────────────────────────────────────────────────

const resumed = restore();
if (!resumed) renderHome();

