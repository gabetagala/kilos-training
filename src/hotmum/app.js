// ─── A session is never used raw ───────────────────────────────────────────
// Two things happen to it first: `progress()` rewrites the work for the day
// of the 100 she's on, and EASY KNEE swaps the knee-dominant blocks out. Every
// caller goes through here so the sheet, the player, the estimate and the
// finish card can never disagree about what she actually did.

// `day` is PINNED on the run rather than read live: a session started at
// 11:55pm must not silently re-prescribe itself when the date rolls over
// mid-set. Everything that rebuilds the queue passes the run's own day back.
const prepped = (id, { easyKnee = false, day } = {}) =>
  sessionForToday(getSession(id), { easyKnee, day });
const runSession = () =>
  prepped(run.sessionId, { easyKnee: run.easyKnee, day: run.day });

